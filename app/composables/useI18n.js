const LOCALES = [
  { id: 'en', label: 'English', dir: 'ltr' },
  { id: 'fa', label: 'فارسی', dir: 'rtl' },
];

export function useI18n() {
  const cookie = useCookie('fw-locale', {
    default: () => 'en',
    maxAge: 60 * 60 * 24 * 365,
    sameSite: 'lax',
  });

  const locale = computed(() =>
    LOCALES.some((entry) => entry.id === cookie.value) ? cookie.value : 'en'
  );
  const dir = computed(() => (locale.value === 'fa' ? 'rtl' : 'ltr'));
  const isRtl = computed(() => dir.value === 'rtl');

  function t(key, params) {
    const table = MESSAGES[locale.value] ?? MESSAGES.en;
    let value = table[key] ?? MESSAGES.en[key] ?? key;
    if (params) {
      for (const [name, replacement] of Object.entries(params)) {
        value = value.replaceAll('{' + name + '}', String(replacement));
      }
    }
    return value;
  }

  function setLocale(next) {
    cookie.value = LOCALES.some((entry) => entry.id === next) ? next : 'en';
  }

  return { locale, dir, isRtl, t, setLocale, locales: LOCALES };
}
